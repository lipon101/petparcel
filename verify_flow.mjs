import { appRouter } from "./server/routers.ts";
import { db } from "./server/_core/db.ts";
import { orders, orderEvents } from "./drizzle/schema.ts";
import { eq } from "drizzle-orm";
const caller = appRouter.createCaller({ user: null, req: {}, res: {} });
const out = {};
const list = await caller.catalog.list({ sort: "newest" });
out.catalogCount = list.length;
out.firstProduct = { name: list[0].name, price: list[0].priceCents, variants: list[0].variants.length, rating: list[0].rating, reviewCount: list[0].reviewCount };
out.categories = await caller.catalog.categories();
out.providers = (await caller.settings.providers()).map(p => p.id);
const p = list[0]; const v = p.variants[0];
const placed = await caller.checkout.place({ email: "jordan.reed@example.com", items: [{ slug: p.slug, variantId: v?.id ?? null, qty: 1 }], shippingAddress: { fullName: "Jordan Reed", line1: "482 Alder Street", line2: null, city: "Portland", state: "OR", postalCode: "97205", country: "US", phone: "5035550142" }, paymentProvider: "2checkout", origin: "https://www.petparcel.store" });
out.placed = { orderNumber: placed.orderNumber, totalCents: placed.totalCents, provider: placed.provider, emailStatus: placed.emailStatus };
const tracked = await caller.orders.lookup({ orderNumber: placed.orderNumber, email: "jordan.reed@example.com" });
out.tracked = { status: tracked.order.status, paymentStatus: tracked.order.paymentStatus, provider: tracked.order.paymentProvider, items: tracked.items.length, total: tracked.order.totalCents, events: tracked.events.length };
const admin = appRouter.createCaller({ user: { id: "admin-verify", role: "admin", name: "Admin", email: "petparcel@proton.me" }, req: {}, res: {} });
const orderRow = (await db.select().from(orders).where(eq(orders.orderNumber, placed.orderNumber)))[0];
await admin.admin.setPaymentStatus({ id: orderRow.id, paymentStatus: "paid", paymentRef: "2CO-VERIFY-1" });
await admin.admin.setOrderStatus({ id: orderRow.id, status: "shipped", note: "Handed to carrier." });
await admin.admin.setTracking({ id: orderRow.id, trackingNumber: "9400111899223857180001", carrier: "USPS", markShipped: true });
const after = (await db.select().from(orders).where(eq(orders.id, orderRow.id)))[0];
const evs = await db.select().from(orderEvents).where(eq(orderEvents.orderId, orderRow.id));
out.adminAfter = { status: after.status, paymentStatus: after.paymentStatus, provider: after.paymentProvider, carrier: after.carrier, tracking: after.trackingNumber, events: evs.length };
const st = await admin.admin.stats();
out.adminStats = { revenue: st.revenueCents ?? st.revenue, orders: st.orderCount ?? st.orders, products: st.productCount ?? st.products };
const prod = await admin.admin.product({ id: p.id });
out.productEditor = { name: prod.name, images: prod.images.length, variants: prod.variants.length };
out.inventoryRows = (await admin.admin.inventory()).length;
out.customers = (await admin.admin.customers()).length;
const s = await caller.settings.public();
out.settings = { announcement: s.announcement, tagline: s.tagline, shipping_estimate: s.shipping_estimate, free_threshold: s.free_shipping_threshold_cents, contact_email: s.contact_email, payment_provider: s.payment_provider };
console.log("RESULT " + JSON.stringify(out));
process.exit(0);
