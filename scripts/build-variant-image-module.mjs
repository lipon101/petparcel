// Generate `shared/variant-images-data.ts` from the REAL production database.
//
// WHY THIS EXISTS. `product_variants.image_url` is populated in production by
// `scripts/sync-variant-images.mjs`, which pulls each variant's own photograph
// from the live CJ API and hosts it on R2. That script needs the live CJ API and
// the R2 credentials, so it cannot run in CI - which means a FRESH database
// (CI's throwaway Postgres, or a brand-new deploy) had NO variant images at all,
// and the auth-and-cart gate that asserts "a cart line carries the picked
// variant's own photo" failed with "none found".
//
// The fix is to make the shipped catalog self-contained: this script reads the
// real, already-synced URLs out of production and writes them into a committed
// data module, so `seedCatalog` can attach them to a fresh database with no CJ
// call and no R2 access. The URLs are REAL (each is the R2 object the CJ
// `variantImage` was re-encoded into) - nothing is invented.
//
// Run:  DATABASE_URL=... node scripts/build-variant-image-module.mjs
import fs from "node:fs";
import path from "node:path";
import pg from "pg";

const DB = process.env.DATABASE_URL;
if (!DB) {
  console.error("DATABASE_URL is required.");
  process.exit(1);
}

const client = new pg.Client({
  connectionString: DB.replace(/[?&]channel_binding=require/, ""),
  ssl: { rejectUnauthorized: false },
});
await client.connect();

// Keyed by SKU: the SKU is the stable, catalog-managed identifier the seeder
// already matches a variant row on, so the map survives a re-seed.
const { rows } = await client.query(
  `select v.sku, v.image_url
     from product_variants v
     join products p on p.id = v.product_id
    where v.image_url is not null
      and v.sku is not null
      and p.active and not p.archived
    order by v.sku`,
);
await client.end();

const entries = rows
  .filter((r) => typeof r.image_url === "string" && r.image_url.startsWith("https://"))
  .map((r) => [r.sku, r.image_url]);

const body = entries
  .map(([sku, url]) => `  ${JSON.stringify(sku)}: ${JSON.stringify(url)},`)
  .join("\n");

const out = `// GENERATED by scripts/build-variant-image-module.mjs - do not edit by hand.
//
// Each variant's OWN product photograph, hosted on our R2 bucket. The URL is the
// R2 object that the live CJ \`variantImage\` for that exact variant was
// re-encoded into (see scripts/sync-variant-images.mjs). Keyed by SKU, the
// catalog-managed identifier the seeder matches a variant row on.
//
// Shipping these in the repo is what lets a FRESH database (CI, a new deploy)
// carry the same real per-variant photos production has, without needing the CJ
// API or the R2 credentials at seed time. Regenerate with:
//   DATABASE_URL=... node scripts/build-variant-image-module.mjs
export const VARIANT_IMAGE_BY_SKU: Record<string, string> = {
${body}
};
`;

const target = path.resolve("shared/variant-images-data.ts");
fs.writeFileSync(target, out);
console.log(`[variant-image-module] wrote ${entries.length} entries to ${target}`);
